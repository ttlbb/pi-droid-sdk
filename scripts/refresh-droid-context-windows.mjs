#!/usr/bin/env node
// Regenerates src/droid-context-windows.generated.ts from the context limits Factory reports.
//
// `availableModels` carries no context length, so the only source is the `limit` that
// `session.getContextStats()` returns per model, which means one short session per model.
// Run it when Factory adds or retires models, with a Factory key available (stored /login
// credential, --api-key, or FACTORY_API_KEY) and the `droid` CLI on PATH:
//
//   npm run refresh:droid-context-windows
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createSession } from "@factory/droid-sdk";
import { readStoredCredential } from "@earendil-works/pi-coding-agent";
import { FALLBACK_MODEL_ITEMS } from "../src/droid-fallback-models.generated.ts";

const CONCURRENCY = 8;
const OUTPUT = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "droid-context-windows.generated.ts");

function resolveApiKey(argv) {
	for (let index = 0; index < argv.length; index += 1) {
		const arg = argv[index];
		const inline = arg.startsWith("--api-key=") ? arg.slice("--api-key=".length) : undefined;
		const value = inline ?? (arg === "--api-key" ? argv[index + 1] : undefined);
		const trimmed = value?.trim();
		if (trimmed) return trimmed;
	}
	const stored = readStoredCredential("factory");
	if (stored?.type === "api_key" && stored.key.trim()) return stored.key.trim();
	return process.env.FACTORY_API_KEY?.trim() || undefined;
}

function isUsableLimit(value) {
	return typeof value === "number" && Number.isFinite(value) && value > 0;
}

const apiKey = resolveApiKey(process.argv.slice(2));
if (!apiKey) {
	console.error("A Factory API key is required: pass --api-key, use /login, or set FACTORY_API_KEY.");
	process.exit(1);
}

const env = { ...process.env, FACTORY_API_KEY: apiKey };
const catalogSession = await createSession({ cwd: process.cwd(), env });
// The bundled fallback catalog also lists models the live catalog may have rotated out, and it is
// what a pi without auth sees, so it is probed as well.
const modelIds = [
	...(catalogSession.initResult.availableModels ?? []).map((item) => item.modelId ?? item.id),
	...FALLBACK_MODEL_ITEMS.map((item) => item.id),
].filter((modelId, index, all) => all.indexOf(modelId) === index);
await catalogSession.close();

const limits = new Map();
let cursor = 0;

async function worker() {
	while (cursor < modelIds.length) {
		const modelId = modelIds[cursor];
		cursor += 1;
		try {
			const session = await createSession({ modelId, cwd: process.cwd(), env });
			try {
				const { limit } = await session.getContextStats();
				if (isUsableLimit(limit)) limits.set(modelId, limit);
				else console.warn(`skip ${modelId}: unusable limit ${String(limit)}`);
			} finally {
				await session.close();
			}
		} catch (error) {
			console.warn(`skip ${modelId}: ${error instanceof Error ? error.message : String(error)}`);
		}
	}
}

await Promise.all(Array.from({ length: CONCURRENCY }, () => worker()));

if (limits.size === 0) {
	console.error("No context limits were reported; keeping the existing snapshot.");
	process.exit(1);
}

const entries = [...limits.entries()]
	.sort(([left], [right]) => left.localeCompare(right))
	.map(([modelId, limit]) => `\t${JSON.stringify(modelId)}: ${limit},`);

const contents = [
	"// Generated by scripts/refresh-droid-context-windows.mjs - do not edit by hand.",
	"// Source: the `limit` Factory reports from `session.getContextStats()` for each live model;",
	"// `availableModels` carries no context length, so it has to be read from one session per model.",
	`// Last regenerated: ${new Date().toISOString().slice(0, 10)}`,
	"export const DROID_CONTEXT_WINDOWS: Record<string, number> = {",
	...entries,
	"};",
	"",
].join("\n");

writeFileSync(OUTPUT, contents);
console.log(`Wrote ${limits.size} context windows to ${OUTPUT}`);
